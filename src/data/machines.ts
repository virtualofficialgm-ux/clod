export function localEquipment(m: Machine, p: Profile, program: Program | null): EquipmentAnalysis {
  let match: EquipmentAnalysis["planMatch"] | null = null;
  program?.days.forEach((d) => {
    const e = d.exercises.find((x) => m.keywords.test(x.name));
    if (e && !match) match = { inPlan: true, dayTitle: d.title, exercise: e.name, sets: e.sets, reps: e.reps, restSec: e.restSec, weightTip: "" };
  });
  const reps = m.cardio ? "15–25 мин" : p.goal === "gain" ? "8–10" : p.goal === "lose" ? "12–15" : "10–12";
  const day = program?.days.find((d) => m.muscles.some((mu) => d.focus.toLowerCase().includes(mu.toLowerCase().slice(0, 5)))) ?? program?.days[0];
  const planMatch: EquipmentAnalysis["planMatch"] = match ?? {
    inPlan: false,
    dayTitle: day?.title ?? "",
    exercise: m.exercise,
    sets: m.cardio ? 1 : p.experience === "beginner" ? 3 : 4,
    reps,
    restSec: m.cardio ? 0 : p.goal === "gain" ? 90 : 60,
    weightTip: "",
  };
  planMatch.weightTip = m.cardio
    ? "Темп, при котором можно говорить короткими фразами."
    : "Начните с веса, с которым последние 2 повтора даются тяжело, но техника не ломается. Добавляйте 1 шаг веса, когда делаете верхнюю границу повторов во всех подходах.";
  return {
    recognized: true,
    name: m.name,
    muscles: m.muscles,
    description: m.description,
    setup: m.setup,
    steps: m.steps,
    mistakes: m.mistakes,
    safety: m.safety,
    planMatch,
    alternatives: m.alternatives,
    coachNote:
      p.experience === "beginner"
        ? "Первые 2 недели работайте с лёгким весом и отрабатывайте технику."
        : "Записывайте вес и повторы: прогресс на тренажёре легко отслеживать.",
  };
}
